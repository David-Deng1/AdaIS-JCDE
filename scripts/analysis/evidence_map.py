"""Evidence table for the results freeze (D8-2, D8-4): every paired effect produced by the analysis scripts, in one
long table with a sign per cell, so each claim in the paper and the response letter can be pointed at a row.

Reads the CSVs written by g2_direction.py (p3_core, p3_edge, p3_ablation), e7_corruption.py, e9a_voi.py, e5_host.py,
e6_uncert.py, e6_fatigue.py, e6_scans.py and bench_eval.py; it computes nothing new. Sign: "+" = AdaIS (side a)
better with the 95% CI excluding zero, "-" = worse, "0" = no detectable difference. rel_pct = advantage / |mean_b|.
The CI is the primary one of te.paired_effect (decision of 10-24): seeds resampled as clusters, so clusters_favour /
n_clusters reads "seeds favouring AdaIS"; the cell-level CI is kept as cell_ci_low / cell_ci_high.

Usage: python evidence_map.py [--out DIR]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_results import PUBLIC  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import jcde_paths  # noqa: E402
RUNS = jcde_paths.P3_RUNS
A = jcde_paths.ANALYSIS
NAMES = {**PUBLIC, "VoI-Timing-MC-AllCh": "VoI-AllCh"}
SOURCES = [  # section, csv, scope column (or None), comparators kept (None = all)
    ("E1 aero P-balanced", "g2/g2_paired_effects.csv", None, None),
    ("E2 aero P-edge", "e2_edge/g2_paired_effects.csv", None, None),
    ("E8 aero nominal ablation", "e_ablation/g2_paired_effects.csv", None, {"AdaS-FixedT8", "AdaS-UniCh", "AdaS-NoQ"}),
    ("E7/E8 common corruption", "e7_corruption/e7_paired_effects.csv", None, None),
    ("E9a VoI all-channel posterior", "e9a_voi_allch/e9a_paired_effects.csv", None, None),
    ("E5 host", "e5_host/e5_paired_effects.csv", ("host", "scope"), None),
    ("E6' uncertainty propagation", "e6_uncert/e6u_paired_effects.csv", None, None),
    ("E6 fatigue form", "e6_fatigue/e6_fatigue_effects.csv", ("form",), None),
    ("E6 scans", "e6_scans/e6s_paired_effects.csv", None, None),
    ("Benchmark", "benchmark/bench_paired_effects.csv", ("problem",), None),
]  # fmt: skip
KEY_METRICS = ["regret_rec", "terminal_hv", "hv_auc", "w_err_l1", "C_cog", "N_int"]


def public(name: str) -> str:
    method, _, variant = str(name).partition("|")
    return NAMES.get(method, method) + (f"|{variant}" if variant else "")


def load() -> pd.DataFrame:
    frames = []
    for section, rel, scope, keep in SOURCES:
        e = pd.read_csv(A / rel)
        if keep:
            e = e[e["b"].isin(keep)]
        e = e.assign(
            section=section,
            scope=e[list(scope)].astype(str).agg("/".join, axis=1) if scope else "",
            a=e["a"].map(public),
            b=e["b"].map(public),
            source=rel,
        )
        frames.append(e)
    t = pd.concat(frames, ignore_index=True)
    t["sign"] = t.apply(
        lambda r: "+" if r["ci_low"] > 0 else ("-" if r["ci_high"] < 0 else "0"), axis=1
    )
    t["rel_pct"] = (
        100 * t["advantage"] / t["mean_b"].abs().where(t["mean_b"].abs() > 1e-12)
    )
    cols = ["section", "scope", "a", "b", "metric", "n", "mean_a", "mean_b", "advantage", "ci_low", "ci_high",
            "clusters_favour", "n_clusters", "rel_pct", "sign", "cell_ci_low", "cell_ci_high", "source"]  # fmt: skip
    return t[cols]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(A / "evidence"))
    out = Path(ap.parse_args().out)
    out.mkdir(parents=True, exist_ok=True)
    t = load()
    t.to_csv(out / "evidence_table.csv", index=False)
    lines = ["# Evidence table (generated by evidence_map.py; do not edit)", "",
             "Sign: + AdaIS better (95% CI excludes 0), - worse, 0 no detectable difference. CI: bootstrap with seeds "
             "as clusters. Cells: advantage [CI] sign (clusters favouring side a / clusters); positive advantage "
             "favours side a.", ""]  # fmt: skip
    k = t[t["metric"].isin(KEY_METRICS)]
    for section, g in k.groupby("section", sort=False):
        lines += [f"## {section}", "", "| scope | a | b | " + " | ".join(KEY_METRICS) + " |",
                  "|" + "---|" * (3 + len(KEY_METRICS))]  # fmt: skip
        for (scope, a, b), h in g.groupby(["scope", "a", "b"], sort=False):
            cell = {
                r.metric: f"{r.advantage:.3g} [{r.ci_low:.3g}, {r.ci_high:.3g}] {r.sign} "
                f"({r.clusters_favour:.0f}/{r.n_clusters:.0f})"
                for r in h.itertuples()
            }
            lines.append(
                f"| {scope} | {a} | {b} | "
                + " | ".join(cell.get(m, "") for m in KEY_METRICS)
                + " |"
            )
        lines.append("")
    (out / "evidence_table.md").write_text("\n".join(lines), encoding="utf-8")
    print(t.groupby(["section", "sign"]).size().unstack(fill_value=0).to_string())
    print(f"{len(t)} effects -> {out}")


if __name__ == "__main__":
    main()
